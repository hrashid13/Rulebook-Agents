# --------------------------------------------------------------------------- the plan

def write_rule(rules, name, *, policy_id, fingerprint="", generated=True, language="python"):
    meta = {"policy": policy_id, "policy_fingerprint": fingerprint}
    if generated:
        meta["generated_by"] = "rulebook-agents"
    rules.mkdir(parents=True, exist_ok=True)
    (rules / f"{name}.yml").write_text(yaml.safe_dump({"rules": [{
        "id": name, "languages": [language], "severity": "INFO", "message": "m",
        "pattern": "x(...)", "metadata": meta}]}))
    (rules / f"{name}.py").write_text("x()\n")


def test_plan_new_changed_unchanged_removed_handwritten(tmp_path):
    rules = tmp_path / "rules"
    pols = parse_policies(POLICIES + "\n## Use pathlib\nlanguages: python, go\n\nUse pathlib for paths.\n")
    by_id = {p.id: p for p in pols}
    write_rule(rules, "no-print-debugging-python", policy_id="no-print-debugging",
               fingerprint=by_id["no-print-debugging"].fingerprint)                    # unchanged
    write_rule(rules, "no-eval-python", policy_id="no-eval", fingerprint="stale")       # changed
    write_rule(rules, "old-policy-python", policy_id="old-policy", fingerprint="x")     # removed
    write_rule(rules, "my-own-pathlib", policy_id="use-pathlib", generated=False)       # hand-written (python)
    plan = make_plan(pols, rules, ())
    assert [(t.policy.id, t.language, t.reason) for t in plan.targets] == [
        ("no-eval", "python", "changed"), ("use-pathlib", "go", "new")]
    assert [r.rule_id for r in plan.unchanged] == ["no-print-debugging-python"]
    assert [r.rule_id for r in plan.remove] == ["old-policy-python"]
    assert [r.rule_id for r in plan.hand_written] == ["my-own-pathlib"]


def test_plan_languages_from_config_or_repo(tmp_path):
    (pol,) = parse_policies("## Use logging\n\nUse logging.\n")
    assert make_plan([pol], tmp_path / "rules", ()).problems[0].startswith('Policy "Use logging" has no languages')
    assert [t.language for t in make_plan([pol], tmp_path / "rules", ("go", "python")).targets] == ["go", "python"]
    repo = tmp_path / "repo"
    (repo / "src").mkdir(parents=True)
    for name in ("a.py", "b.py", "c.ts", "README.md", ".rulebook/rules/x.java"):
        (repo / name).parent.mkdir(parents=True, exist_ok=True)
        (repo / name).write_text("x")
    git(repo, "init", "-q")
    git(repo, "add", "-A")
    assert detect_languages(repo) == ("python", "typescript")      # most files first; .rulebook/ ignored


def test_plan_only_some_policies(tmp_path):
    write_rule(tmp_path / "rules", "gone-python", policy_id="gone", fingerprint="x")
    plan = make_plan(parse_policies(POLICIES), tmp_path / "rules", (), only={"no-eval"})
    assert [t.policy.id for t in plan.targets] == ["no-eval"] and plan.remove == []   # no deletes when filtered


def test_apply_writes_passing_rules_and_removes_old_ones(tmp_path):
    from rulebook.synthesize import SynthResult
    rules = tmp_path / "rules"
    write_rule(rules, "old-python", policy_id="old", fingerprint="x")
    plan = make_plan(parse_policies(POLICIES), rules, ())
    results = [SynthResult("no-print-debugging", "python", "no-print-debugging-python", True,
                           rule_yaml="rules: []\n", test_code="print(1)\n", attempts=1, matched_lines=[1]),
               SynthResult("no-eval", "python", "no-eval-python", False, attempts=3, error="did not match")]
    apply(plan, results, rules)
    assert sorted(p.name for p in rules.iterdir()) == ["no-print-debugging-python.py", "no-print-debugging-python.yml"]
    md = summary_markdown(plan, results, parse_policies(POLICIES))
    assert "| No print debugging | python | new | passed: matched 1 violation" in md
    assert "No eval (python), 3 attempts: did not match" in md and "`old-python`" in md


