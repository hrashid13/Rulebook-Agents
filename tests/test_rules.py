POLICIES = """# Team rules

## No print debugging
category: style
languages: python
severity: info

Use the logging module instead of print() in application code.

## No eval
category: security
languages: python
severity: error

Never pass strings to eval(). It runs arbitrary code.
"""

PATTERNS = {"no-print-debugging": "print(...)", "no-eval": "eval(...)"}
VIOLATION = {"no-print-debugging": ('print("got", x)', 'print(x)'), "no-eval": ("eval(x)", 'eval("1+" + x)')}
COMPLIANT = {"no-print-debugging": ('log.info("got %s", x)', "pprint = 1"),
             "no-eval": ("int(x)", "evaluate = 1")}


def good_answer(rule_id: str) -> str:
    policy = rule_id.rsplit("-", 1)[0]
    bad1, bad2 = VIOLATION[policy]
    ok1, ok2 = COMPLIANT[policy]
    return (f"```yaml\nrules:\n  - id: wrong-id\n    languages: [python]\n    severity: ERROR\n"
            f"    message: Not allowed by the policy.\n    pattern: {PATTERNS[policy]}\n```\n\n"
            f"```python\nimport logging\nlog = logging.getLogger(__name__)\n\n\ndef f(x):\n"
            f"    # ruleid: {rule_id}\n    {bad1}\n    # ruleid: {rule_id}\n    {bad2}\n"
            f"    # ok: {rule_id}\n    {ok1}\n    # ok: {rule_id}\n    {ok2}\n```")


class SynthModel:
    """Writes a correct rule for the rule id in the prompt. `first` replaces the first answer
    (per rule id) to make an attempt fail; `always_bad` makes every attempt fail."""

    def __init__(self, first: str | None = None, always_bad: bool = False):
        self.first, self.always_bad = first, always_bad
        self.calls: list[dict] = []
        self.seen: set[str] = set()

    def complete(self, *, model, system, messages, temperature, max_tokens):
        self.calls.append({"messages": messages, "max_tokens": max_tokens})
        rule_id = re.search(r"rule id `([^`]+)`", messages[0]["content"]).group(1)
        if self.always_bad or (self.first is not None and rule_id not in self.seen):
            self.seen.add(rule_id)
            text = self.first if self.first is not None else good_answer(rule_id).replace(
                PATTERNS[rule_id.rsplit("-", 1)[0]], "open(...)")
            return RawCompletion(text, "end_turn", 300, 200)
        return RawCompletion(good_answer(rule_id), "end_turn", 300, 200)


def synth_llm(tmp_path, model=None) -> LLMClient:
    return LLMClient(mode="live", cache_dir=tmp_path / "cache", backend=model or SynthModel())


def policy(name="no-print-debugging"):
    return {p.id: p for p in parse_policies(POLICIES)}[name]


