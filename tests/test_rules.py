# --------------------------------------------------------------------------- the Action's rules flow

class FakePulls:
    def __init__(self):
        self.pulls: list[dict] = []
        self.comments: list[tuple[int, str]] = []

    def handler(self, request: httpx.Request) -> httpx.Response:
        path = request.url.path
        if request.method == "GET" and path.endswith("/pulls"):
            head = request.url.params["head"].split(":", 1)[1]
            return httpx.Response(200, json=[p for p in self.pulls if p["head"] == head and p["state"] == "open"])
        if request.method == "POST" and path.endswith("/pulls"):
            body = json.loads(request.content)
            pr = {"number": 10 + len(self.pulls), "state": "open", **body}
            self.pulls.append(pr)
            return httpx.Response(201, json=pr)
        if request.method == "PATCH" and "/pulls/" in path:
            n = int(path.rsplit("/", 1)[1])
            pr = next(p for p in self.pulls if p["number"] == n)
            pr.update(json.loads(request.content))
            return httpx.Response(200, json=pr)
        if request.method == "POST" and path.endswith("/comments"):
            self.comments.append((int(path.split("/")[-2]), json.loads(request.content)["body"]))
            return httpx.Response(201, json={"id": 1})
        return httpx.Response(404, json={"message": "Not Found"})

    def client(self) -> GitHub:
        return GitHub("t", "acme/shop", http=httpx.Client(base_url="https://api.github.com",
                                                         transport=httpx.MockTransport(self.handler)))


def make_origin(tmp_path, policies=POLICIES):
    """A bare 'GitHub' repo and the runner's checkout of its default branch."""
    seed = tmp_path / "seed"
    (seed / ".rulebook").mkdir(parents=True)
    (seed / ".rulebook" / "policies.md").write_text(policies)
    (seed / "app.py").write_text("print('hi')\n")
    git(seed, "init", "-q")
    git(seed, "add", "-A")
    git(seed, "commit", "-q", "-m", "policies")
    origin = tmp_path / "origin.git"
    git(tmp_path, "clone", "-q", "--bare", str(seed), str(origin))
    work = tmp_path / "work"
    git(tmp_path, "clone", "-q", str(origin), str(work))
    return origin, work


def rules_env(tmp_path, work, *, ref="main", event="push"):
    runner = tmp_path / "runner"
    runner.mkdir(exist_ok=True)
    (runner / "event.json").write_text(json.dumps({"repository": {"default_branch": "main"}}))
    return {"GITHUB_EVENT_NAME": event, "GITHUB_EVENT_PATH": str(runner / "event.json"),
            "GITHUB_REPOSITORY": "acme/shop", "GITHUB_REF_NAME": ref, "GITHUB_WORKSPACE": str(work),
            "RUNNER_TEMP": str(runner), "GITHUB_STEP_SUMMARY": str(runner / "summary.md"),
            "GITHUB_OUTPUT": str(runner / "out.txt"), "RULEBOOK_GITHUB_TOKEN": "t"}


def run_rules(env, fake, tmp_path, model=None):
    out = io.StringIO()
    code = Action(env, github=fake.client(), llm=synth_llm(tmp_path, model), out=out).run()
    return code, out.getvalue()


@needs_semgrep
def test_rules_flow_opens_a_pull_request(tmp_path):
    origin, work = make_origin(tmp_path)
    fake = FakePulls()
    code, log = run_rules(rules_env(tmp_path, work), fake, tmp_path)
    assert code == 0 and "pull request #10 has 2 rule(s)" in log
    (pr,) = fake.pulls
    assert pr["head"] == RULES_BRANCH and pr["base"] == "main" and pr["title"] == "Rulebook: rules for 2 policies"
    assert "Merging this pull request is what puts them" in pr["body"] and "| No eval | python | new |" in pr["body"]
    files = git(origin, "ls-tree", "-r", "--name-only", RULES_BRANCH).split()
    assert ".rulebook/rules/no-eval-python.yml" in files and ".rulebook/rules/no-eval-python.py" in files
    assert git(origin, "log", "-1", "--format=%ae", RULES_BRANCH).strip() == BOT_EMAIL
    assert ".rulebook/rules" not in git(origin, "ls-tree", "-r", "--name-only", "main")   # main untouched


@needs_semgrep
def test_running_again_updates_the_same_pull_request(tmp_path):
    origin, work = make_origin(tmp_path)
    fake = FakePulls()
    run_rules(rules_env(tmp_path, work), fake, tmp_path)
    git(work, "checkout", "-q", "main")
    run_rules(rules_env(tmp_path, work, event="workflow_dispatch"), fake, tmp_path)
    assert len(fake.pulls) == 1


@needs_semgrep
def test_never_overwrites_commits_people_pushed(tmp_path):
    origin, work = make_origin(tmp_path)
    fake = FakePulls()
    run_rules(rules_env(tmp_path, work), fake, tmp_path)
    person = tmp_path / "person"
    git(tmp_path, "clone", "-q", "-b", RULES_BRANCH, str(origin), str(person))
    (person / ".rulebook" / "rules" / "no-eval-python.yml").write_text("# tuned by hand\n")
    git(person, "commit", "-qam", "tune the rule")
    git(person, "push", "-q", "origin", RULES_BRANCH)
    tip = git(origin, "rev-parse", RULES_BRANCH)
    git(work, "checkout", "-q", "main")
    code, log = run_rules(rules_env(tmp_path, work, event="workflow_dispatch"), fake, tmp_path)
    assert code == 0 and "not overwriting" in log
    assert git(origin, "rev-parse", RULES_BRANCH) == tip                 # the person's commit is still there
    assert fake.comments and "1 commit pushed by people" in fake.comments[0][1]
    assert "example.com" not in fake.comments[0][1]                   # no one's email is posted


@needs_semgrep
def test_failed_rules_are_listed_and_the_rest_still_ship(tmp_path):
    origin, work = make_origin(tmp_path)

    class EvalAlwaysBad(SynthModel):
        def complete(self, **kw):
            out = super().complete(**kw)
            if "no-eval-python" in kw["messages"][0]["content"]:
                return RawCompletion(out.text.replace("eval(...)", "open(...)"), "end_turn", 1, 1)
            return out
    fake = FakePulls()
    code, _ = run_rules(rules_env(tmp_path, work), fake, tmp_path, EvalAlwaysBad())
    (pr,) = fake.pulls
    assert code == 0 and "(1 need a hand-written rule)" in pr["title"]
    assert "No eval (python), 3 attempts" in pr["body"]
    files = git(origin, "ls-tree", "-r", "--name-only", RULES_BRANCH).split()
    assert ".rulebook/rules/no-print-debugging-python.yml" in files and not any("no-eval" in f for f in files)


