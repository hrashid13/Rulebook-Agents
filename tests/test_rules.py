@needs_semgrep
def test_synthesizes_a_tested_rule(tmp_path):
    r = synthesize(policy(), "python", synth_llm(tmp_path))
    assert r.ok and r.attempts == 1 and r.matched_lines == [7, 9]
    rule = yaml.safe_load(r.rule_yaml)["rules"][0]
    # code, not the model, decides these
    assert rule["id"] == "no-print-debugging-python" and rule["languages"] == ["python"]
    assert rule["severity"] == "INFO" and rule["metadata"]["policy"] == "no-print-debugging"
    assert rule["metadata"]["policy_fingerprint"] == policy().fingerprint
    assert r.rule_yaml.startswith("# Generated by Rulebook Agents")


@needs_semgrep
def test_a_failing_test_goes_back_to_the_model(tmp_path):
    model = SynthModel(first=None)
    model.first = good_answer("no-print-debugging-python").replace("print(...)", "log.info(...)")
    r = synthesize(policy(), "python", synth_llm(tmp_path, model))
    assert r.ok and r.attempts == 2
    feedback = model.calls[1]["messages"][-1]["content"]
    assert "did not match these `ruleid:` lines: line 7: 'print(\"got\", x)'" in feedback
    assert "matched lines it should not: line 11: 'log.info(\"got %s\", x)'" in feedback


